/* ═══════════════════════════════════════════════════════════════════════════
   THE TEST PLAN RUNNER.

   Executes every case in tests/plan/ and writes two things:

     tests/TEST-PLAN.md      the plan on its own — intent and expectation,
                             readable and reviewable before anything runs
     tests/TEST-RESULTS.md   the same plan with the ACTUAL result and a verdict
                             against each case

   Both are GENERATED from the case files. A written plan maintained separately
   from the checks it describes drifts, and then the document says one thing
   while the suite does another — which is the exact failure mode this whole
   suite was built to catch, so it would be poor form to build it in here.

   Usage:  node tests/run-test-plan.js          run everything, write both docs
           node tests/run-test-plan.js --plan   write the plan only, run nothing
   ═══════════════════════════════════════════════════════════════════════════ */
'use strict';
const { requirePlaywright, chromePath, APP } = require('./_harness');
const fs = require('fs'), path = require('path');

const NUMBERS = require('./plan/cases-numbers');
const BEHAVIOUR = require('./plan/cases-behaviour');
const ROOT = path.resolve(__dirname, '..');
const QA = JSON.parse(fs.readFileSync(path.join(ROOT, 'fixtures', 'qa-reference.json'), 'utf8'));
const CRM = JSON.parse(fs.readFileSync(path.join(ROOT, 'fixtures', 'crm-rollout.json'), 'utf8'));

const wrap = (s, w) => {
  const out = []; let line = '';
  String(s).split(/\s+/).forEach(word => {
    if ((line + ' ' + word).trim().length > w) { out.push(line.trim()); line = word; }
    else line += ' ' + word;
  });
  if (line.trim()) out.push(line.trim());
  return out.join('\n');
};
const show = v => {
  if (v === undefined) return '_(not produced)_';
  if (typeof v === 'object' && v !== null) {
    return Object.keys(v).map(k => `\`${k}\` = ${JSON.stringify(v[k])}`).join(' · ');
  }
  return '`' + JSON.stringify(v) + '`';
};

// deep compare with a tolerance for numbers
function same(exp, got, tol) {
  const t = tol == null ? 1e-9 : tol;
  if (typeof exp === 'number' && typeof got === 'number') return Math.abs(exp - got) <= t;
  if (Array.isArray(exp)) return Array.isArray(got) && exp.length === got.length
    && exp.every((e, i) => same(e, got[i], t));
  if (exp && typeof exp === 'object') {
    if (!got || typeof got !== 'object') return false;
    return Object.keys(exp).every(k => same(exp[k], got[k], t));
  }
  return exp === got;
}

function planDoc(results) {
  const stamp = results ? results.stamp : null;
  const L = [];
  L.push('# Test plan — expected values and behaviour against design intent');
  L.push('');
  L.push('_Generated from `tests/plan/cases-numbers.js` and `tests/plan/cases-behaviour.js`._');
  L.push('_Do not edit this file: edit the cases and re-run `node tests/run-test-plan.js`._');
  L.push('');
  L.push('Every case states three things: what the application is **meant** to do and why');
  L.push('(the design intent), what that means **numerically or behaviourally** (the');
  L.push('expectation), and where the expectation came from. The expectation is derived from');
  L.push('the fixture inputs by hand, not read out of a run — so you can disagree with the');
  L.push('expectation itself, which is the only way a test can catch an application that is');
  L.push('confidently and self-consistently wrong.');
  L.push('');
  L.push('**Fixtures.** `qa-reference.json` is a five-activity plan whose inputs were chosen so');
  L.push('every derived number is a whole number checkable on paper. `crm-rollout.json` is a');
  L.push('real export, carrying the shape the sample never had: a baseline taken after the work');
  L.push('started, so activities finish before their own baseline windows open.');
  L.push('');
  if (results) {
    const n = results.cases.length, pass = results.cases.filter(c => c.status === 'PASS').length;
    L.push(`**Last run:** ${stamp} — **${pass} of ${n} passing**`
      + (pass === n ? '.' : `, **${n - pass} FAILING**.`));
    L.push('');
  }
  L.push('---');
  L.push('');

  const byArea = {};
  const all = [].concat(
    NUMBERS.map(c => Object.assign({ kind: 'number' }, c)),
    BEHAVIOUR.map(c => Object.assign({ kind: 'behaviour' }, c)));
  all.forEach(c => { (byArea[c.area] = byArea[c.area] || []).push(c); });

  Object.keys(byArea).forEach(area => {
    L.push(`## ${area}`); L.push('');
    byArea[area].forEach(c => {
      const r = results && results.cases.find(x => x.id === c.id);
      const verdict = r ? (r.status === 'PASS' ? '✅ PASS' : '❌ **FAIL**') : '';
      L.push(`### ${c.id} — ${c.title}${verdict ? '  ' + verdict : ''}`);
      L.push('');
      L.push('**Design intent.** ' + wrap(c.intent, 88));
      L.push('');
      L.push('**Expected.** ' + show(c.expect));
      L.push('');
      if (c.from) { L.push('**Derived from.** ' + c.from); L.push(''); }
      if (r) {
        L.push('**Actual.** ' + show(r.actual));
        if (r.status !== 'PASS') {
          L.push('');
          L.push('> **This case failed.** ' + (r.error ? 'It threw: `' + r.error + '`'
            : 'The application does not do what the intent above describes.'));
        }
        L.push('');
      }
    });
  });
  return L.join('\n') + '\n';
}

(async () => {
  const planOnly = process.argv.indexOf('--plan') >= 0;
  if (planOnly) {
    fs.writeFileSync(path.join(__dirname, 'TEST-PLAN.md'), planDoc(null));
    console.log('wrote tests/TEST-PLAN.md (plan only, nothing executed)');
    return;
  }

  const { chromium } = requirePlaywright();
  const b = await chromium.launch({headless:true,args:['--no-sandbox'],executablePath: chromePath()});
  const page = await b.newPage({viewport:{width:1440,height:1200}});
  page.on('dialog', d => d.accept());
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.goto(APP, {waitUntil:'load'});
  await page.evaluate(([qa, crm]) => { window.__qa = qa; window.__crm = crm; },
    [QA, CRM]);

  const cases = [];

  // ── the NUMBER cases all read one snapshot of the QA reference plan ────
  await page.evaluate(d => { hydrate(d); calculate(); }, QA);
  await page.waitForTimeout(700);
  const snap = await page.evaluate(() => {
    const hb = hasBaseline(), today = stripTime(new Date()).getTime();
    const acts = {};
    leafTasks().forEach(t => {
      const days = t.milestone ? 0 : unitToWorkingDays(t.te || 0);
      acts[t.name] = { te: t.te, variance: t.variance, es: t.es, ef: t.ef, ls: t.ls, lf: t.lf,
        slack: t.slack, critical: !!t.isCritical,
        startDate: t.startDate ? fmtISO(t.startDate) : null,
        finishDate: t.finishDate ? fmtISO(t.finishDate) : null,
        cost: taskCost(t),
        revenue: taskParticipants(t).reduce((s, pr) =>
          s + (isClientResource(pr.name) ? 0 : getBillRate(pr.name) * days * pr.units / 100), 0) };
    });
    const f = pricingFigures(), rl = computeResourceLoad();
    const AC = leafTasks().reduce((s, t) => s + actualCostOf(t), 0);
    const PV = accrualAt(pvSpread(hb, leafTasks()).segs, today);
    const EV = earnedValue();
    const c = tasks.find(t => t.name === 'C Docs');
    const sp = c.percentComplete, sa = c.actualCost;
    c.percentComplete = 0; c.actualCost = 0; calculate();
    const rl2 = computeResourceLoad();
    const live = { days: rl2.overResourceDays, people: rl2.resourcesOver.slice(),
      dates: [...new Set(Object.values(rl2.perResource).flatMap(R => R.overDays || []))].sort() };
    c.percentComplete = sp; c.actualCost = sa; calculate();
    return { activities: acts,
      projectDurationDays: Math.max(0, ...leafTasks().map(t => t.ef), 0),
      criticalPath: leafTasks().filter(t => t.isCritical).sort((a, x) => a.es - x.es).map(t => t.name),
      projectCost: projectCost(), projectRevenue: f.detRev, marginPct: f.margin,
      evm: { pv: PV, ev: EV, ac: AC, cv: EV - AC, svMoney: EV - PV, gapAgainstPlanToDate: AC - PV },
      resourcingAsShipped: rl.overResourceDays, resourcingWithCUnfinished: live };
  });

  NUMBERS.forEach(c => {
    let actual, error = null;
    try { actual = c.check(snap); } catch (e) { error = e.message; }
    const ok = !error && same(c.expect, actual, c.tol);
    cases.push({ id: c.id, area: c.area, title: c.title,
      status: ok ? 'PASS' : 'FAIL', actual, error });
  });

  // ── the BEHAVIOUR cases each set up their own state ────────────────────
  for (const c of BEHAVIOUR) {
    let actual, error = null;
    try {
      // a clean slate before each, so one case cannot poison the next
      await page.evaluate(d => { hydrate(d); calculate(); }, QA);
      actual = await page.evaluate(src => (0, eval)('(' + src + ')')(), c.fn);
    } catch (e) { error = String(e.message || e).slice(0, 200); }
    const ok = !error && same(c.expect, actual, c.tol);
    cases.push({ id: c.id, area: c.area, title: c.title,
      status: ok ? 'PASS' : 'FAIL', actual, error });
  }

  const stamp = await page.evaluate(() =>
    (document.getElementById('buildStamp') || {}).textContent || '(no build stamp)');
  await b.close();

  const results = { stamp: String(stamp).trim(), cases, pageErrors: errs.slice(0, 8) };
  fs.writeFileSync(path.join(__dirname, 'TEST-PLAN.md'), planDoc(null));
  fs.writeFileSync(path.join(__dirname, 'TEST-RESULTS.md'), planDoc(results));

  const pass = cases.filter(c => c.status === 'PASS').length;
  console.log(JSON.stringify({
    build: results.stamp,
    total: cases.length, passed: pass, failed: cases.length - pass,
    failures: cases.filter(c => c.status !== 'PASS')
      .map(c => ({ id: c.id, title: c.title, expected: undefined, actual: c.actual, error: c.error })),
    pageErrors: results.pageErrors,
  }, null, 1));
  if (pass !== cases.length || errs.length) process.exitCode = 1;
})();
